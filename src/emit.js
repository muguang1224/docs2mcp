/**
 * Write a self-contained, runnable MCP server directory.
 *
 * Output is dependency-free on purpose: `node server.mjs` must work on a fresh
 * machine with no `npm install`, no lockfile, and no network access.
 */

import { mkdir, writeFile, readFile, stat } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { json, bytes, serverNameFor } from './util.js';

const SERVER_TEMPLATE = new URL('./templates/server.mjs', import.meta.url);
const RUNTIME_SOURCE = new URL('./mcp-runtime.js', import.meta.url);

function slugFor(hostname) {
  return `${serverNameFor(hostname)}-mcp`;
}

function generatedReadme({ index, dir, serverPath }) {
  const { stats, source, generatedAt } = index;
  const clientKey = serverNameFor(new URL(source).hostname);
  const config = {
    mcpServers: {
      [clientKey]: { command: 'node', args: [serverPath] },
    },
  };
  const snippet = JSON.stringify(config, null, 2);

  return `# ${new URL(source).hostname} — MCP server

Generated by [docs2mcp](https://github.com/muguang1224/docs2mcp) from <${source}>.

| | |
|---|---|
| Pages | ${stats.pages} |
| Passages | ${stats.chunks} |
| Text | ${bytes(stats.chars)} |
| Generated | ${generatedAt} |

## Run it

\`\`\`bash
node server.mjs
\`\`\`

It speaks MCP over stdio, so it is meant to be launched by a client, not by hand.

## Add it to your MCP client

Use this config block. The path is absolute, so it works from anywhere.

\`\`\`json
${snippet}
\`\`\`

| Client | Where the config goes |
|---|---|
| Claude Desktop | \`claude_desktop_config.json\` in your app support folder |
| Claude Code | \`claude mcp add --transport stdio ${clientKey} -- node ${serverPath}\` |
| Cursor | \`.cursor/mcp.json\` |
| VS Code (Copilot) | \`.vscode/mcp.json\` |
| Cline / Windsurf | their MCP settings file |

## Tools

| Tool | What it does |
|---|---|
| \`search_docs\` | BM25 search over ${stats.chunks} passages, returns passages + source URLs |
| \`get_page\` | Full cleaned Markdown of one page |
| \`list_pages\` | Inventory of all ${stats.pages} pages |

## Regenerate

\`\`\`bash
npx docs2mcp ${source}
\`\`\`

\`index.json\` is a plain data file, so you can diff it, commit it, or cache it in CI.
`;
}

export async function emit({ index, outDir, source }) {
  const dir = resolve(outDir);
  await mkdir(dir, { recursive: true });

  const serverCode = await readFile(SERVER_TEMPLATE, 'utf8');
  const runtimeCode = await readFile(RUNTIME_SOURCE, 'utf8');
  const serverPath = join(dir, 'server.mjs');
  const packageName = slugFor(new URL(source).hostname);

  const files = [];

  await writeFile(serverPath, serverCode, 'utf8');
  files.push({ name: 'server.mjs', size: Buffer.byteLength(serverCode) });

  await writeFile(join(dir, 'runtime.mjs'), runtimeCode, 'utf8');
  files.push({ name: 'runtime.mjs', size: Buffer.byteLength(runtimeCode) });

  const indexJson = JSON.stringify(index);
  await writeFile(join(dir, 'index.json'), indexJson, 'utf8');
  files.push({ name: 'index.json', size: Buffer.byteLength(indexJson) });

  const pkg = json({
    name: packageName,
    version: '1.0.0',
    private: true,
    type: 'module',
    description: `MCP server for ${source}, generated by docs2mcp`,
    scripts: { start: 'node server.mjs' },
  });
  await writeFile(join(dir, 'package.json'), pkg, 'utf8');
  files.push({ name: 'package.json', size: Buffer.byteLength(pkg) });

  const mcpConfig = json({
    mcpServers: {
      [serverNameFor(new URL(source).hostname)]: { command: 'node', args: [serverPath] },
    },
  });
  await writeFile(join(dir, 'mcp.json'), mcpConfig, 'utf8');
  files.push({ name: 'mcp.json', size: Buffer.byteLength(mcpConfig) });

  const readme = generatedReadme({ index, dir, serverPath });
  await writeFile(join(dir, 'README.md'), readme, 'utf8');
  files.push({ name: 'README.md', size: Buffer.byteLength(readme) });

  return { dir, serverPath, files };
}

export async function directoryIsEmptyOrMissing(dir) {
  try {
    const info = await stat(dir);
    if (!info.isDirectory()) return false;
    const { readdir } = await import('node:fs/promises');
    const entries = await readdir(dir);
    return entries.length === 0;
  } catch {
    return true;
  }
}
